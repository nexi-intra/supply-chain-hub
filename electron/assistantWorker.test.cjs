function slowClient(t, options = {}) {
  const state = { platformRoot: 'synthetic', activeDir: 'synthetic', currentFolder: 'ONE' }
  const client = createAssistantWorkerClient({ getState: () => state, workerPath: path.join(__dirname, 'fixtures', 'assistantSlowWorker.cjs'), timeoutMs: 2000, ...options })
  t.after(() => client.stop())
  return { client, state }
}
test('a synchronously blocked child leaves the parent responsive and gets timed out', async t => {
  const { client } = slowClient(t)
  await client.session().moduleCatalog()
  let ticks = 0
  const timer = setInterval(() => ticks++, 20)
  t.after(() => clearInterval(timer))
  await assert.rejects(() => client.session().query({ question: 'slow' }), /tog for lang tid/)
  assert.ok(ticks >= 5, 'Parent event loop must continue while child storage is blocked')
  assert.deepEqual(await client.session().moduleCatalog(), { synthetic: true })
})
test('stop cancels pending work and prevents an old request session from restarting the worker', async t => {
  const { client } = slowClient(t)
  const session = client.session()
  const pending = session.query({ question: 'slow' })
  client.stop()
  await assert.rejects(() => pending, /afbrudt/)
  await assert.rejects(() => session.authorize('valid'), /afbrudt/)
  assert.deepEqual(await client.session().moduleCatalog(), { synthetic: true })
})
test('ordinary panel close/cancel preserves an idle worker and does not cancel guide preparation', async t => {
  const { client } = slowClient(t)
  const session = client.session()
  await session.moduleCatalog()
  client.cancel()
  assert.deepEqual(await session.moduleCatalog(), { synthetic: true })
  const preparation = session.prepare({ token: 'synthetic' })
  client.cancel()
  assert.deepEqual(await preparation, { synthetic: true })
})
test('scope changes reject in-flight results; worker crashes return an error instead of hanging', async t => {
  const { client, state } = slowClient(t)
  const session = client.session()
  state.currentFolder = 'TWO'
  await assert.rejects(() => session.query({ question: 'anything' }), /Hubben blev ændret/)
  await assert.rejects(() => client.session().query({ question: 'crash' }), /baggrundsproces stoppede/)
  assert.deepEqual(await client.session().moduleCatalog(), { synthetic: true })
})
