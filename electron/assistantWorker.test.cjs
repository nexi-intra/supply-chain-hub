const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const registry = require('./registry.cjs')
const { createStore } = require('./store.cjs')
const { createWorkerRuntime } = require('./assistantWorker.cjs')
const { createAssistantWorkerClient } = require('./assistantWorkerClient.cjs')
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sch-assistant-test-'))
  t.after(() => {
    const target = path.resolve(root)
    assert.ok(target.startsWith(path.resolve(os.tmpdir()) + path.sep + 'sch-assistant-test-'))
    fs.rmSync(target, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 })
  })
  registry.createTeam(root, { teamId: 'ONE', name: 'Synthetic One', folderName: 'ONE' })
  registry.createTeam(root, { teamId: 'TWO', name: 'Synthetic Two', folderName: 'TWO' })
  const [one, two] = registry.listTeams(root)
  registry.assignUserToTeam(root, 'me@test', 'ONE')
  const store = createStore(path.join(root, one.folderName))
  const outside = createStore(path.join(root, two.folderName))
  const shared = createStore(path.join(root, '_shared'))
  store.set('users', { 'me@test': { email: 'me@test', fullName: 'Synthetic User', status: 'approved', role: 'user' } })
  store.set('guides', [{ id: 'cloud', title: 'Cloud guide', version: '1.00', content: 'Den nye cloud ip adresse er 192.0.2.10. SYNTHETIC_ONLY' }])
  outside.set('guides', [{ id: 'other', title: 'Cloud external', content: 'OUTSIDE_GUIDE_SECRET' }])
  shared.set('active-sessions', { valid: { email: 'me@test', expiresAt: Date.now() + 60000 } })
  const config = { platformRoot: root, currentFolder: one.folderName, activeDir: store.dataDir, localDir: path.join(root, '_local'), diagnostics: { version: 'test', connected: true } }
  const runtime = createWorkerRuntime()
  const request = { token: 'valid', question: 'hvad er den nye cloud ip adresse', language: 'da' }
  const query = () => runtime.call('query', [request], config)
  return { root, store, shared, outside, one, two, config, runtime, request, query }
}
test('real worker runtime reuses guide cache and retrieves the exact reported question', t => {
  const { query, runtime } = fixture(t)
  const first = query()
  const second = query()
  assert.equal(first.mode, 'retrieval')
  assert.match(second.text, /192\.0\.2\.10/)
  assert.ok(runtime.stats().hits >= 1)
  assert.ok(!second.text.includes('OUTSIDE_GUIDE_SECRET'))
  assert.ok(!JSON.stringify(second.sources).includes('words'))
})

test('historical follow-up rechecks current role and detects edits of the same snapshot', t => {
  const { runtime, store, config, request } = fixture(t)
  store.set('users', { 'me@test': { email: 'me@test', fullName: 'Synthetic User', status: 'approved', role: 'manager' } })
  store.set('guide-versions-cloud', [{ version: '0.99', snapshot: { content: 'NY CLOUD IP ADRESSE 192.0.2.30' } }])
  const followup = { ...request, question: 'hvad er den gamle så?', conversation: [request.question] }
  const evidence = runtime.call('query', [followup], config)
  assert.ok(evidence.sources.some(source => source.history))
  runtime.call('revalidateSources', [followup, evidence], config)
  store.set('guide-versions-cloud', [{ version: '0.99', snapshot: { content: 'NY CLOUD IP ADRESSE 192.0.2.40' } }])
  assert.throws(() => runtime.call('revalidateSources', [followup, evidence], config), /historikken blev ændret/)
  store.set('users', { 'me@test': { email: 'me@test', fullName: 'Synthetic User', status: 'approved', role: 'user' } })
  assert.throws(() => runtime.call('revalidateSources', [followup, evidence], config), /ikke adgang/)
  assert.ok(!runtime.call('query', [followup], config).sources.some(source => source.history))
})
test('login preparation warms only authorized published guides before the first question', t => {
  const { runtime, config, request, store, query } = fixture(t)
  store.set('guide-review-requests', [{ id: 'draft', status: 'pending', submittedBy: 'me@test', proposedGuide: { title: 'Cloud draft', content: 'DRAFT_NOT_PUBLISHED' } }])
  const prepared = runtime.call('prepare', [request], config)
  assert.deepEqual(prepared, { guideCount: 1, stepCount: 1 })
  assert.ok(!JSON.stringify(prepared).includes('192.0.2.10'))
  assert.equal(runtime.stats().entries, 1)
  const hits = runtime.stats().hits
  const answer = query()
  assert.ok(runtime.stats().hits > hits)
  assert.ok(!answer.text.includes('DRAFT_NOT_PUBLISHED'))
  assert.ok(!answer.text.includes('OUTSIDE_GUIDE_SECRET'))
})
