const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { createPreparedFiles, PREPARED_FILE_PATTERN } = require('./preparedFiles.cjs')

function folder(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-prepared-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  return dir
}
const preparedIn = dir => fs.readdirSync(dir).filter(name => PREPARED_FILE_PATTERN.test(name))

test('takeTmp returns null on the first call, then a ready empty file after refill', async t => {
  const dir = folder(t)
  const pool = createPreparedFiles()
  assert.equal(pool.takeTmp(dir), null, 'never waits for a preparation')
  await pool.whenIdle()
  const file = pool.takeTmp(dir)
  assert.ok(file && fs.existsSync(file))
  assert.equal(fs.statSync(file).size, 0)
  assert.equal(path.dirname(file), dir)
  assert.match(path.basename(file), PREPARED_FILE_PATTERN)
  assert.ok(!file.endsWith('.json') && !file.endsWith('.json.lock'))
  assert.doesNotMatch(path.basename(file), /\.json\.\d+\.(\d+)\.[0-9a-f]{8}\.tmp$/)
  await pool.closeAll()
})

test('takeOwner gives each lock its own owner id, written in the file', async t => {
  const dir = folder(t)
  const pool = createPreparedFiles()
  pool.takeOwner(dir)
  await pool.whenIdle()
  const first = pool.takeOwner(dir)
  const second = pool.takeOwner(dir)
  assert.ok(first && second)
  assert.notEqual(first.file, second.file)
  assert.notEqual(first.owner, second.owner)
  assert.equal(fs.readFileSync(first.file, 'utf8'), first.owner)
  assert.equal(fs.readFileSync(second.file, 'utf8'), second.owner)
  await pool.closeAll()
})

test('releaseOwner reusable writes a new id into the same file and returns it to the pool', async t => {
  const dir = folder(t)
  const pool = createPreparedFiles({ poolSize: 1 })
  pool.takeOwner(dir)
  await pool.whenIdle()
  const entry = pool.takeOwner(dir)
  await pool.whenIdle()
  pool.releaseOwner(dir, entry, { reusable: true })
  await pool.whenIdle()
  const again = pool.takeOwner(dir)
  assert.equal(again.file, entry.file, 'the same file, no new one')
  assert.notEqual(again.owner, entry.owner)
  assert.equal(fs.readFileSync(again.file, 'utf8'), again.owner)
  await pool.closeAll()
})

test('releaseOwner not reusable deletes the file and never hands it out again', async t => {
  const dir = folder(t)
  const pool = createPreparedFiles({ poolSize: 1 })
  pool.takeOwner(dir)
  await pool.whenIdle()
  const entry = pool.takeOwner(dir)
  pool.releaseOwner(dir, entry, { reusable: false })
  await pool.whenIdle()
  assert.ok(!fs.existsSync(entry.file))
  const next = pool.takeOwner(dir)
  assert.ok(next)
  assert.notEqual(next.file, entry.file)
  await pool.closeAll()
})

test('want raises the pool for a folder up to maxPoolSize', async t => {
  const dir = folder(t)
  const pool = createPreparedFiles({ poolSize: 2, maxPoolSize: 12 })
  pool.want(dir, 9)
  await pool.whenIdle()
  const owners = Array.from({ length: 9 }, () => pool.takeOwner(dir))
  assert.ok(owners.every(Boolean))
  assert.equal(new Set(owners.map(entry => entry.file)).size, 9)
  pool.want(dir, 50)
  await pool.whenIdle()
  const tmps = []
  for (let file = pool.takeTmp(dir); file; file = pool.takeTmp(dir)) tmps.push(file)
  assert.equal(tmps.length, 12)
  await pool.closeAll()
})

test('a failing drive leaves the pool empty without unhandled rejections', async t => {
  const dir = folder(t)
  const rejections = []
  const onRejection = error => rejections.push(error)
  process.on('unhandledRejection', onRejection)
  t.after(() => process.off('unhandledRejection', onRejection))
  const broken = { ...fs.promises, open: async () => { throw Object.assign(new Error('drive gone'), { code: 'EIO' }) } }
  const pool = createPreparedFiles({ fsp: broken })
  assert.equal(pool.takeTmp(dir), null)
  assert.equal(pool.takeOwner(dir), null)
  await pool.whenIdle()
  assert.equal(pool.takeTmp(dir), null)
  await pool.whenIdle()
  await new Promise(resolve => setImmediate(resolve))
  assert.deepEqual(rejections, [])
})

test('closeAll removes every ready file', async t => {
  const dir = folder(t)
  const pool = createPreparedFiles()
  pool.takeTmp(dir)
  pool.takeOwner(dir)
  await pool.whenIdle()
  assert.ok(preparedIn(dir).length >= 4)
  await pool.closeAll()
  assert.deepEqual(preparedIn(dir), [])
  assert.equal(pool.takeTmp(dir), null, 'a closed pool prepares nothing')
  await pool.whenIdle()
  assert.deepEqual(preparedIn(dir), [])
})
