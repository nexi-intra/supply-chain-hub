const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { createStore } = require('./store.cjs')
const { eraseUserData } = require('./userErasure.cjs')

const GONE = 'gone@test'
function fixture() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'erase-'))
  const store = createStore(dir)
  store.set('shift-assignments', [{ id: 'a1', employeeId: GONE }, { id: 'a2', employeeId: 'stay@test' }, { id: 'a3', employeeId: 'GONE@test' }])
  store.set('shift-patterns', [{ id: 'p1', employeeId: GONE }, { id: 'p2', employeeId: 'stay@test' }])
  store.set('vacation-entries', [{ id: 'v1', userEmail: GONE }, { id: 'v2', userEmail: 'stay@test' }])
  store.set('sick-leave-entries', [{ id: 's1', userEmail: GONE }])
  store.set('home-office-exceptions', [{ id: 'h1', userEmail: GONE }, { id: 'h2', userEmail: 'stay@test' }])
  store.set('home-office-patterns', { [GONE]: { weekdays: [1] }, 'stay@test': { weekdays: [2] } })
  store.set('user-settings', { [GONE]: { phoneNumber: '1' }, 'stay@test': { phoneNumber: '2' } })
  store.set('employee-birthdays', [{ id: 'b1', email: GONE }, { id: 'b2', email: 'stay@test' }])
  store.set('emails', [{ id: 'm1', from: 'stay@test', to: GONE }, { id: 'm2', from: GONE, to: 'stay@test' }, { id: 'm3', from: 'stay@test', to: 'other@test' }])
  store.set('email-folders', [{ id: 'f1', userId: GONE }, { id: 'f2', userId: 'stay@test' }])
  store.set('notebook-notes', [{ id: 'n1', isPersonal: true, creatorEmail: GONE }, { id: 'n2', isPersonal: false, creatorEmail: GONE }, { id: 'n3', isPersonal: true, creatorEmail: 'stay@test' }])
  store.set('email-notifications', [{ id: 'e1', to: GONE }, { id: 'e2', to: 'stay@test' }])
  store.set(`todos-personal-${GONE}`, [{ id: 't1' }])
  store.set(`hub-dashboard-${GONE}`, {})
  store.set(`app-language-user_${GONE}`, 'da')
  store.set('todos-personal-stay@test', [{ id: 't2' }])
  store.set('todos-personal-xgone@test', [{ id: 't3' }])
  store.set('guides', [{ id: 'g1', author: GONE }])
  return { store, dir }
}

test('removes everything the team store holds about a deleted person, and nothing about anyone else', async () => {
  const { store, dir } = fixture()
  const result = await eraseUserData(store, 'Gone@Test')
  const ids = key => (store.get(key, { skipCache: true }) || []).map(item => item.id)
  assert.deepEqual(ids('shift-assignments'), ['a2'])
  assert.deepEqual(ids('shift-patterns'), ['p2'])
  assert.deepEqual(ids('vacation-entries'), ['v2'])
  assert.deepEqual(ids('sick-leave-entries'), [])
  assert.deepEqual(ids('home-office-exceptions'), ['h2'])
  assert.deepEqual(Object.keys(store.get('home-office-patterns', { skipCache: true })), ['stay@test'])
  assert.deepEqual(Object.keys(store.get('user-settings', { skipCache: true })), ['stay@test'])
  assert.deepEqual(ids('employee-birthdays'), ['b2'])
  // Their inbox goes; what they sent stays with the recipients.
  assert.deepEqual(ids('emails'), ['m2', 'm3'])
  assert.deepEqual(ids('email-folders'), ['f2'])
  assert.deepEqual(ids('notebook-notes'), ['n2', 'n3'])
  assert.deepEqual(ids('email-notifications'), ['e2'])
  for (const key of [`todos-personal-${GONE}`, `hub-dashboard-${GONE}`, `app-language-user_${GONE}`]) assert.equal(store.get(key, { skipCache: true }), undefined, key)
  assert.deepEqual(ids('todos-personal-stay@test'), ['t2'])
  assert.deepEqual(ids('todos-personal-xgone@test'), ['t3'])
  assert.deepEqual(ids('guides'), ['g1'])
  assert.equal(result.records, 13)
  assert.equal(result.keys, 3)
  fs.rmSync(dir, { recursive: true, force: true })
})

test('an empty or missing e-mail erases nothing', async () => {
  const { store, dir } = fixture()
  assert.deepEqual(await eraseUserData(store, '  '), { records: 0, keys: 0 })
  assert.equal(store.get('shift-assignments', { skipCache: true }).length, 3)
  fs.rmSync(dir, { recursive: true, force: true })
})
