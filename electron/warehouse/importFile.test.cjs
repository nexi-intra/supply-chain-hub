const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const ExcelJS = require('exceljs')
const { readSerialFile } = require('./importFile.cjs')
const { createFixtureRunner } = require('./sapFixtures.cjs')
const { createSapBridge } = require('./sapBridge.cjs')
const { createSapFetcher } = require('./sapFetch.cjs')

const tempDir = () => fs.mkdtempSync(path.join(os.tmpdir(), 'countpoint-import-'))

test('text and CSV files: one serial per line, header and other columns are recognised', async () => {
  const dir = tempDir()
  fs.writeFileSync(path.join(dir, 'a.txt'), '\uFEFFN1\r\nN2\n\n N3 \n')
  assert.deepEqual((await readSerialFile(path.join(dir, 'a.txt'))).serials, ['N1', 'N2', 'N3'])
  fs.writeFileSync(path.join(dir, 'b.csv'), 'Materiale;Serienummer;Antal\nINT1;S1;1\nINT1;S2;1\n')
  assert.deepEqual((await readSerialFile(path.join(dir, 'b.csv'))).serials, ['S1', 'S2'])
})

test('Excel files: the serial column is found by its header, otherwise the first column is used', async () => {
  const dir = tempDir()
  const withHeader = new ExcelJS.Workbook()
  const sheet = withHeader.addWorksheet('Ark1')
  sheet.addRow(['Palle', 'Serial Number'])
  sheet.addRow(['14.2', 'S1'])
  sheet.addRow(['14.2', 12345])
  await withHeader.xlsx.writeFile(path.join(dir, 'a.xlsx'))
  const result = await readSerialFile(path.join(dir, 'a.xlsx'))
  assert.deepEqual(result.serials, ['S1', '12345'])
  assert.equal(result.fileName, 'a.xlsx')
  const plain = new ExcelJS.Workbook()
  plain.addWorksheet('Ark1').addRows([['P1'], ['P2']])
  await plain.xlsx.writeFile(path.join(dir, 'b.xlsx'))
  assert.deepEqual((await readSerialFile(path.join(dir, 'b.xlsx'))).serials, ['P1', 'P2'])
})

test('a 24-digit serial in a file counts as its last 18 digits, as when it is scanned', async () => {
  const dir = tempDir()
  fs.writeFileSync(path.join(dir, 'a.txt'), '251427303201349258058038\n2514273032013492580580381\nN1\n')
  assert.deepEqual((await readSerialFile(path.join(dir, 'a.txt'))).serials, ['303201349258058038', '2514273032013492580580381', 'N1'])
})

test('unsupported or too large files are refused', async () => {
  const dir = tempDir()
  fs.writeFileSync(path.join(dir, 'x.exe'), 'MZ')
  await assert.rejects(readSerialFile(path.join(dir, 'x.exe')), { code: 'IMPORT_FILE_TYPE' })
  fs.writeFileSync(path.join(dir, 'big.txt'), 'x')
  await assert.rejects(readSerialFile(path.join(dir, 'big.txt'), { maxBytes: 0 }), { code: 'IMPORT_FILE_TOO_LARGE' })
})

test('the SAP fixture runner feeds the real fetch pipeline (for E2E without SAP)', async () => {
  const runScript = createFixtureRunner(path.join(__dirname, 'fixtures', 'sap'))
  const bridge = createSapBridge({ runScript })
  assert.equal((await bridge.status()).state, 'ready')
  const result = await createSapFetcher({ bridge, runScript, tempRoot: tempDir() }).fetchPlant()
  assert.ok(result.mb52.length > 0)
  assert.ok(result.serials.length > 0)
})
