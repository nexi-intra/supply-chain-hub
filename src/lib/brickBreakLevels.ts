export function brickPatternForLevel(level: number, rows: number): boolean[][] {
  const pattern = LEVEL_PATTERNS[(Math.max(1, level) - 1) % LEVEL_PATTERNS.length]
  return Array.from({ length: rows }, (_, row) => {
    const sourceRow = rows <= 1 ? 0 : Math.round(row * (pattern.length - 1) / (rows - 1))
    return [...pattern[sourceRow]].map(cell => cell === '#')
  })
}
